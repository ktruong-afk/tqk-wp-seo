pat = re.compile(r"(?:__|esc_html__|esc_attr__)\(\s*'((?:[^'\\]|\\.)*)'")
used = set()
for f in list((ROOT / 'src').rglob('*.php')):
    used |= set(pat.findall(f.read_text(encoding='utf-8')))

pot_p = ROOT / 'languages' / 'tqk-wpseo.pot'
msgid = re.compile(r'msgid "((?:[^"\\]|\\.)*)"')
pot_ids = set(msgid.findall(pot_p.read_text(encoding='utf-8')))
added = 0
with open(pot_p, 'a', encoding='utf-8') as fh:
    for s in sorted(used - pot_ids):
        if s == '':
            continue
        fh.write(f'\nmsgid "{s}"\nmsgstr ""\n')
        added += 1
print('pot-added:', added)

po_p = ROOT / 'languages' / 'tqk-wpseo-vi.po'
po = po_p.read_text(encoding='utf-8')
filled = 0
for en, vi in TR.items():
    if f'msgid "{en}"' not in po:
        po += f'\nmsgid "{en}"\nmsgstr "{vi}"\n'
        filled += 1
        continue
    # fill empty msgstr if present
    old = f'msgid "{en}"\nmsgstr ""'
    if old in po:
        po = po.replace(old, f'msgid "{en}"\nmsgstr "{vi}"', 1)
        filled += 1
po_p.write_text(po, encoding='utf-8')
print('vi-filled:', filled)
missing_tr = sorted(used - set(TR.keys()) - pot_ids)
print('strings-without-vi:', missing_tr)
